export default `No campo de escrita há o botão ** a folha**. Ele reescreve o seu rascunho **antes** de
enviar.

**Como usar:**

1. Escreva a ideia, mesmo bagunçada.
2. Clique na folha e escolha o modo.
3. O texto volta reescrito **na caixa** — você revisa e só então envia.

:::dica
**Nada é enviado ao Koda.** A folha é uma chamada de texto puro: ela **não** entra no
histórico e **não** executa nada. É um rascunho melhorado, e você decide se usa.

### Os cinco modos

A ordem no menu é a de uso: o primeiro é o do dia a dia.

| Modo | O que faz | Quando serve |
| --- | --- | --- |
|  **Melhorar com base** | Mantém o que você escreveu e **acrescenta o que falta** | **O de todo dia.** A base está boa, só precisa subir |
|  **Criar do zero** | Escreve o prompt **inteiro** a partir da ideia solta | Você só tem um lampejo: *"queria uma tela de login bonita"* |
|  **Estrutura** | Separa as tarefas e organiza, sem reescrever | A ideia é boa mas está tudo embolado num parágrafo |
|  **Melhorar a fala** | Deixa mais claro e direto, sem mudar o pedido | Só a escrita está ruim; o pedido está certo |
|  **Acentuar e pontuar** | **Só** corrige acentos e pontuação | Você digitou com pressa no celular |

### O que um prompt melhor tem

Quando você usa a folha nos modos que reescrevem tudo, ela organiza o texto assim:

1. **O objetivo** — o que deve ser feito, em uma frase
2. **O contexto** — o que importa saber sobre o projeto, o ambiente e o motivo
3. **As instruções** — os passos em ordem, com detalhe suficiente para executar
4. **A validação** — o que verificar **para este pedido**

:::dica
**Você pode usar essa estrutura de cabeça.** Mesmo sem a folha, um pedido que tem
objetivo + contexto + passos + como conferir funciona muito melhor.

###  Dois comportamentos que valem conhecer

**1. Vários pedidos viram tarefas separadas.**

Se você escrever *"conserta o botão da foto"* e *"resolve o 404"* no mesmo texto, a folha
**separa em Tarefa 1 e Tarefa 2**, cada uma completa e independente.

:::dica
**Aproveite isso.** Juntar vários pedidos num rascunho só é uma boa forma de trabalhar: a
folha organiza em tarefas separadas, e o Koda ataca uma por uma em vez de misturar os assuntos.

**2. A validação é só a necessária.**

A folha cobre só o que **este** pedido precisa verificar. Num pedido sobre um botão torto,
ela valida o botão — não o carrinho de compras inteiro.

:::dica
**Ela pode citar os seus recursos.** Se você tem MCPs, skills ou sub-agentes ativos, a
folha pode incluí-los na validação quando fizerem sentido — por exemplo, "conferir no Painel
Dev" quando o MCP \`navegador\` está ligado. **Ela não inventa recurso que você não tem.**`
