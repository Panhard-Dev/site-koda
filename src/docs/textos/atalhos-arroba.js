export default `Digite **\`@\`** em **qualquer lugar** do texto (não precisa ser no começo). A sintaxe é
**\`@tipo.nome\`**:

| Você digita | O que significa |
| --- | --- |
| \`@sub.revisor\` | Quem faz isto é **aquele sub-agente** |
| \`@skill.validar-front\` | **Siga as instruções** desta skill |
| \`@mcp.navegador\` | **Use este servidor** |

:::dica
**A menção é tratada como ORDEM.** O Koda leva a marca a sério: \`@mcp.navegador\` é "use
este servidor", não "talvez considere".

:::dica
**O ponto filtra a lista sem abrir menu.** \`@mcp.\` mostra só os servidores; \`@sk\` filtra
por skill.

:::dica
**Você reconhece a marca pela cor**, e a cor é a mesma na lista e no texto:
 **sub-agente** ·  **MCP** ·  **skill**.

:::dica
**Skill e MCP desligados não aparecem.** Marcar o que está desligado seria pedir uma coisa
que o Koda não alcança.

:::atencao
**Um \`@\` no meio de um e-mail não é menção.** \`a@b.com\` não abre o menu — a marca tem de
estar no começo do texto ou depois de um espaço.`
