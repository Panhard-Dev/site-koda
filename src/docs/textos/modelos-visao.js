export default `Alguns modelos conseguem **ver imagens**, outros não. Isso muda completamente o que você
pode pedir.

**O que muda na prática:**

| Recurso | Precisa de visão? |
| --- | --- |
| Mandar um print e perguntar "o que está errado aqui?" |  Sim |
| Mandar uma foto de um layout e pedir para reproduzir |  Sim |
| **Ver os quadros de um vídeo anexado** |  Sim |
| Ler um PDF (o texto) |  Não |
| Analisar um CSV |  Não |

:::dica
**Se a imagem "não for entendida", é o modelo.** Nem todo modelo do catálogo tem visão.
Se você mandou um print e o Koda respondeu como se não houvesse imagem, troque para um modelo
com visão.

:::dica
**Para vídeo isso é decisivo.** Ver [videos/](../videos/): os quadros só entram no
contexto quando o modelo enxerga.`
